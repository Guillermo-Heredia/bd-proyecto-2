-- Se borra todo antes de crear para poder re-ejecutar el script.
DROP TABLE IF EXISTS AlertaOrden, OrdenTrabajo, AlertaMantenimiento, Tecnico,
  LecturaVibracion, SensorVibracion, ComponenteTurbina, Turbina, ParqueEolico CASCADE;

CREATE TABLE ParqueEolico (
  id_parque        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(100) NOT NULL,
  ubicacion        VARCHAR(150) NOT NULL,
  capacidad_mw     DECIMAL(10,2) NOT NULL CHECK (capacidad_mw > 0),
  fecha_operacion  DATE NOT NULL
);

CREATE TABLE Turbina (
  id_turbina        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_parque         INT NOT NULL REFERENCES ParqueEolico(id_parque),
  codigo            VARCHAR(30) NOT NULL UNIQUE,
  fabricante        VARCHAR(60) NOT NULL,
  modelo            VARCHAR(60) NOT NULL,
  capacidad_kw      DECIMAL(10,2) NOT NULL CHECK (capacidad_kw > 0),
  fecha_instalacion DATE NOT NULL,
  estado            VARCHAR(20) NOT NULL
    CHECK (estado IN ('Operativa','Detenida','Mantenimiento'))
);

CREATE TABLE ComponenteTurbina (
  id_componente     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_turbina        INT NOT NULL REFERENCES Turbina(id_turbina),
  nombre            VARCHAR(60) NOT NULL,
  tipo              VARCHAR(40) NOT NULL,
  ubicacion_interna VARCHAR(60) NOT NULL,
  estado            VARCHAR(20) NOT NULL
);

CREATE TABLE SensorVibracion (
  id_sensor             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_componente         INT NOT NULL REFERENCES ComponenteTurbina(id_componente),
  codigo                VARCHAR(30) NOT NULL UNIQUE,
  modelo                VARCHAR(50) NOT NULL,
  unidad_medida         VARCHAR(20) NOT NULL,
  frecuencia_muestreo_hz DECIMAL(10,2) NOT NULL CHECK (frecuencia_muestreo_hz > 0),
  fecha_instalacion     DATE NOT NULL,
  estado                VARCHAR(20) NOT NULL
    CHECK (estado IN ('Activo','Inactivo','Mantenimiento'))
);

CREATE TABLE LecturaVibracion (
  id_sensor   INT NOT NULL REFERENCES SensorVibracion(id_sensor),
  fecha_hora  TIMESTAMP NOT NULL,
  valor_rms   DECIMAL(12,4) NOT NULL CHECK (valor_rms >= 0),
  valor_pico  DECIMAL(12,4) NOT NULL CHECK (valor_pico >= 0),
  frecuencia_dominante_hz DECIMAL(12,4) NOT NULL CHECK (frecuencia_dominante_hz >= 0),
  PRIMARY KEY (id_sensor, fecha_hora)
);

CREATE TABLE Tecnico (
  id_tecnico   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres      VARCHAR(100) NOT NULL,
  especialidad VARCHAR(60) NOT NULL,
  correo       VARCHAR(100) NOT NULL UNIQUE,
  telefono     VARCHAR(15)
);

CREATE TABLE AlertaMantenimiento (
  id_alerta          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sensor          INT NOT NULL REFERENCES SensorVibracion(id_sensor),
  fecha_hora_lectura TIMESTAMP,
  fecha_hora         TIMESTAMP NOT NULL,
  nivel              VARCHAR(15) NOT NULL
    CHECK (nivel IN ('Baja','Media','Alta','Critica')),
  tipo_alerta        VARCHAR(50) NOT NULL,
  valor_detectado    DECIMAL(12,4) NOT NULL,
  descripcion        VARCHAR(255) NOT NULL,
  estado             VARCHAR(20) NOT NULL
    CHECK (estado IN ('Abierta','En revision','Cerrada')),
  FOREIGN KEY (id_sensor, fecha_hora_lectura)
    REFERENCES LecturaVibracion(id_sensor, fecha_hora)
);

CREATE TABLE OrdenTrabajo (
  id_orden           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_turbina         INT NOT NULL REFERENCES Turbina(id_turbina),
  id_tecnico         INT REFERENCES Tecnico(id_tecnico),
  fecha_creacion     TIMESTAMP NOT NULL,
  fecha_programada   TIMESTAMP,
  fecha_cierre       TIMESTAMP,
  prioridad          VARCHAR(15) NOT NULL
    CHECK (prioridad IN ('Baja','Media','Alta','Critica')),
  tipo_mantenimiento VARCHAR(50) NOT NULL
    CHECK (tipo_mantenimiento IN ('Inspeccion','Preventivo','Correctivo')),
  descripcion        VARCHAR(255) NOT NULL,
  estado             VARCHAR(20) NOT NULL
    CHECK (estado IN ('Pendiente','En proceso','Finalizada','Cancelada')),
  CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_creacion),
  CHECK (estado NOT IN ('En proceso','Finalizada') OR id_tecnico IS NOT NULL),
  CHECK (estado <> 'Finalizada' OR fecha_cierre IS NOT NULL)
);

CREATE TABLE AlertaOrden (
  id_alerta BIGINT NOT NULL REFERENCES AlertaMantenimiento(id_alerta),
  id_orden  BIGINT NOT NULL REFERENCES OrdenTrabajo(id_orden),
  PRIMARY KEY (id_alerta, id_orden)
);
